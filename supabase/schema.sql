/** ログイン中の利用者（メールアドレス）。未ログイン・未許可ならエラー */
create or replace function exo.require_user() returns text
language plpgsql stable set search_path = '' as $$
declare
  v_email text := lower(btrim(coalesce(auth.jwt() ->> 'email', '')));
begin
  if auth.uid() is null or v_email = '' then
    raise exception using errcode = '42501', message = 'ログインしてください。';
  end if;
  if not exists (select 1 from exo.app_user u where u.email = v_email and u.is_active) then
    raise exception using errcode = '42501',
      message = 'このアカウント（' || v_email || '）には利用権限がありません。管理者に利用者登録を依頼してください。';
  end if;
  return v_email;
end $$;

