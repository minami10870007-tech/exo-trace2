/** ロット番号（社内・仕入先どちらでも、部分一致）→ 出荷先顧客。p = { query } */
create or replace function public.trace_lot(p jsonb default '{}') returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_q text := upper(coalesce(exo.j_text(p, 'query'), ''));
begin
  perform exo.require_user();
  if v_q = '' then perform exo.fail('ロット番号を入力してください。'); end if;
  return coalesce((
    select jsonb_agg(v.j || jsonb_build_object(
      'inventory', coalesce((select jsonb_agg(jsonb_build_object('location', loc.name, 'qty', i.on_hand_qty) order by loc.id)
                             from exo.t_inventory i join exo.m_location loc on loc.id = i.location_id
                             where i.lot_id = l.id and i.on_hand_qty <> 0), '[]'),
      'shipments', coalesce((select jsonb_agg(jsonb_build_object(
                               'customer_code', c.customer_code, 'customer', c.name, 'phone', c.phone, 'email', c.email,
                               'shipment_no', s.shipment_no, 'shipped_on', s.shipped_on, 'status', sl.status, 'quantity', sl.quantity,
                               'returned', exo.returned_qty(sl.id, false), 'recalled', exo.returned_qty(sl.id, true),
                               'net', case when sl.status = 'SHIPPED' then sl.quantity - exo.returned_qty(sl.id) else 0 end)
                             order by s.shipped_on, sl.id)
                             from exo.t_shipment_line sl
                             join exo.t_shipment s on s.id = sl.shipment_id
                             join exo.m_customer c on c.id = s.customer_id
                             where sl.lot_id = l.id), '[]'),
      'movementTotals', coalesce((select jsonb_object_agg(m.movement_type, m.total)
                                  from (select movement_type, sum(quantity) as total from exo.t_stock_movement
                                        where lot_id = l.id group by movement_type) m), '{}'),
      'history', coalesce((select jsonb_agg(jsonb_build_object('id', h.id, 'from_status', h.from_status, 'to_status', h.to_status,
                             'reason', h.reason, 'changed_at', exo.fmt_ts(h.changed_at), 'changed_by', h.changed_by) order by h.id)
                           from exo.t_lot_status_history h where h.lot_id = l.id), '[]'))
      order by l.id)
    from (select * from exo.t_lot
          where strpos(upper(lot_no), v_q) > 0 or strpos(upper(supplier_lot_no), v_q) > 0
          order by id limit 20) l
    join exo.v_lot v on v.id = l.id), '[]');
end $$;

/** 顧客 → 購入ロット。p = { customerId, from, to } */
create or replace function public.trace_customer(p jsonb default '{}') returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_customer exo.m_customer;
  v_from date := exo.to_date(exo.j_text(p, 'from'));
  v_to date := exo.to_date(exo.j_text(p, 'to'));
begin
  perform exo.require_user();
  select * into v_customer from exo.m_customer where id = exo.j_id(p, 'customerId');
  if v_customer.id is null then perform exo.fail('顧客を選択してください。'); end if;
  if (exo.j_text(p, 'from') is not null and v_from is null) or (exo.j_text(p, 'to') is not null and v_to is null) then
    perform exo.fail('期間の日付が不正です。');
  end if;
  return jsonb_build_object(
    'customer', to_jsonb(v_customer) - 'created_at' - 'updated_at',
    'rows', coalesce((select jsonb_agg(jsonb_build_object(
        'shipped_on', s.shipped_on, 'shipment_no', s.shipment_no, 'product', pr.name, 'lot_no', l.lot_no,
        'supplier_lot_no', l.supplier_lot_no, 'expires_on', l.expires_on, 'lot_status', l.status,
        'lot_status_label', exo.code_label('lot_status', l.status), 'quantity', sl.quantity,
        'returned', exo.returned_qty(sl.id), 'net', sl.quantity - exo.returned_qty(sl.id))
        order by s.shipped_on desc, s.id desc, sl.id)
      from exo.t_shipment s
      join exo.t_shipment_line sl on sl.shipment_id = s.id
      join exo.t_lot l on l.id = sl.lot_id
      join exo.m_product pr on pr.id = sl.product_id
      where s.customer_id = v_customer.id and s.status = 'SHIPPED' and sl.status = 'SHIPPED'
        and (v_from is null or s.shipped_on >= v_from) and (v_to is null or s.shipped_on <= v_to)), '[]'));
end $$;

-- ---- 回収（P-08 / P-14 / P-18 / P-19 の簡易版） ----

/** p = { title, reason, severity, lotIds: [] } */
create or replace function public.create_recall(p jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_user text := exo.require_user();
  v_title text := exo.j_text(p, 'title');
  v_reason text := exo.j_text(p, 'reason');
  v_severity text := exo.j_text(p, 'severity');
  v_ids bigint[];
  v_today date := exo.today();
  v_recall_id bigint;
  v_recall_no text;
  l record;
begin
  perform exo.write_lock();
  if v_title is null or v_reason is null then perform exo.fail('件名と回収理由は必須です。'); end if;
  if v_severity is null or v_severity not in ('I', 'II', 'III') then perform exo.fail('重大度（クラスI/II/III）を選択してください。'); end if;
  if jsonb_typeof(p -> 'lotIds') = 'array' then
    select array_agg(distinct exo.j_id(jsonb_build_object('v', x), 'v')) into v_ids
    from jsonb_array_elements(p -> 'lotIds') x where exo.trim_text(x #>> '{}') is not null;
  end if;
  if v_ids is null or cardinality(v_ids) = 0 then perform exo.fail('対象ロットを1件以上選択してください。'); end if;
  if array_position(v_ids, null) is not null or (select count(*) from exo.t_lot where id = any (v_ids)) <> cardinality(v_ids) then
    perform exo.fail('ロットが見つかりません。画面を再読込してください。');
  end if;
  if exists (select 1 from exo.t_lot where id = any (v_ids) and status = 'VOID') then
    perform exo.fail('無効（VOID）のロットは回収対象に指定できません。');
  end if;
  v_recall_no := 'RCL-' || to_char(v_today, 'YYYY') || '-' || lpad((coalesce((select max(substr(recall_no, 10)::integer) from exo.t_recall
    where recall_no like 'RCL-' || to_char(v_today, 'YYYY') || '-%' and substr(recall_no, 10) ~ '^\d{1,9}$'), 0) + 1)::text, 3, '0');
  insert into exo.t_recall (recall_no, title, reason, severity, started_on, status, created_by)
  values (v_recall_no, v_title, v_reason, v_severity, v_today, 'OPEN', v_user)
  returning id into v_recall_id;
  for l in select id, status from exo.t_lot where id = any (v_ids) order by id for update loop
    insert into exo.t_recall_lot (recall_id, lot_id) values (v_recall_id, l.id);
    if l.status <> 'RECALLED' then
      perform exo.set_lot_status(l.id, 'RECALLED', '回収 ' || v_recall_no || '：' || v_reason, v_user);
    end if;
  end loop;
  perform exo.extract_targets(v_recall_id);
  return exo.recall_view(v_recall_id);
end $$;

