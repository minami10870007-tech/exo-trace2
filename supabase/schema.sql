-- =============================================================================
-- EXO-TRACE Supabase 版 データベース定義
--
--   エクソソーム製品の 入荷 → 受入検品 → 出荷（FEFO自動引当） → 返品 → ロット/顧客追跡 → 回収
--   をロット単位で管理する。業務ルールはすべてこのファイルの関数（RPC）に実装している。
--
-- 使い方（ターミナル不要）
--   1. Supabase ダッシュボード「SQL Editor」→「New query」にこのファイルの内容をすべて貼り付けて「Run」
--      （何度実行しても既存データは消えません。更新版を貼り直すときも同じ手順です）
--   2. 「Authentication」→「Users」→「Add user」→「Create new user」で利用者を作成（Auto Confirm User にチェック）
--   3. SQL Editor で、利用を許可するメールアドレスを登録する（人数分）
--        insert into exo.app_user (email) values ('taro@example.com');
--
-- 構成
--   exo スキーマ … テーブルと内部関数。API（PostgREST）には公開しない
--   public スキーマ … 画面から呼ぶ関数（RPC）だけを置く。ログイン済みかつ exo.app_user に登録された利用者のみ実行できる
--
-- 設計書との対応：詳細設計書 v1.3 の簡易版（段階導入）。発注・受注伝票、納品先、ロール別権限、
--   合格済ロットへの分納、温度記録、添付ファイルは本格版で実装する。
-- =============================================================================

create schema if not exists exo;
revoke all on schema exo from public;

