create or replace function exo.trim_text(p_value text) returns text
language sql immutable set search_path = '' as $$
  select nullif(btrim(p_value, E' \t\r\n' || chr(12288)), '')
$$;

/** 文字列（前後の空白を除去、空なら null） */
create or replace function exo.j_text(p jsonb, k text) returns text
language sql immutable set search_path = '' as $$
  select case when p is null or jsonb_typeof(p) <> 'object' or jsonb_typeof(p -> k) is null or jsonb_typeof(p -> k) = 'null' then null
              else exo.trim_text(p ->> k) end
$$;

/** 数値（未入力は null、数値でなければ NaN） */
create or replace function exo.j_num(p jsonb, k text) returns numeric
language plpgsql immutable set search_path = '' as $$
declare v text := exo.j_text(p, k);
begin
  if v is null then return null; end if;
  if v !~ '^[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?$' or length(v) > 30 then return 'NaN'; end if;
  return v::numeric;
exception when others then
  return 'NaN';
end $$;

/** ID（数字でなければ null） */
create or replace function exo.j_id(p jsonb, k text) returns bigint
language sql immutable set search_path = '' as $$
  select case when exo.j_text(p, k) ~ '^\d{1,18}$' then exo.j_text(p, k)::bigint end
$$;

create or replace function exo.j_bool(p jsonb, k text) returns boolean
language sql immutable set search_path = '' as $$
  select coalesce(lower(exo.j_text(p, k)) in ('true', '1'), false)
$$;

/** YYYY-MM-DD の日付（不正なら null） */
create or replace function exo.to_date(p_text text) returns date
language plpgsql immutable set search_path = '' as $$
begin
  if p_text is null or p_text !~ '^\d{4}-\d{2}-\d{2}$' then return null; end if;
  return p_text::date;
exception when others then
  return null;
end $$;

/** 1以上の整数 */
create or replace function exo.pos_int(p_value numeric, p_label text) returns integer
language plpgsql immutable set search_path = '' as $$
begin
  if p_value is null or p_value = 'NaN' or p_value <= 0 or p_value <> trunc(p_value) or p_value > 1000000000 then
    perform exo.fail(p_label || 'は1以上の整数で入力してください。');
  end if;
  return p_value::integer;
end $$;

/** 伝票番号 例: SH-202610-0001 */
create or replace function exo.next_no(p_prefix text, p_date date, p_existing text[]) returns text
language sql immutable set search_path = '' as $$
  select p_prefix || '-' || to_char(p_date, 'YYYYMM') || '-' || lpad((coalesce(max(substr(n, length(p_prefix) + 9)::integer), 0) + 1)::text, 4, '0')
  from unnest(p_existing) n
  where n like p_prefix || '-' || to_char(p_date, 'YYYYMM') || '-%' and substr(n, length(p_prefix) + 9) ~ '^\d+$'
$$;

/** 在庫を増減し、在庫移動履歴を記録する（BR-02：在庫は必ず移動履歴と一緒に更新） */
create or replace function exo.move(p_type text, p_lot_id bigint, p_location_id bigint, p_qty integer,
  p_ref_type text, p_ref_id bigint, p_reason text, p_by text) returns void
language plpgsql volatile set search_path = '' as $$
declare v_cur integer;
begin
  select on_hand_qty into v_cur from exo.t_inventory where lot_id = p_lot_id and location_id = p_location_id for update;
  if coalesce(v_cur, 0) + p_qty < 0 then
    perform exo.fail('在庫が不足しています（ロット ' || coalesce((select lot_no from exo.t_lot where id = p_lot_id), p_lot_id::text) ||
      '、保管場所 ' || coalesce((select name from exo.m_location where id = p_location_id), p_location_id::text) || '）。');
  end if;
  insert into exo.t_inventory (lot_id, location_id, on_hand_qty) values (p_lot_id, p_location_id, coalesce(v_cur, 0) + p_qty)
  on conflict (lot_id, location_id) do update set on_hand_qty = excluded.on_hand_qty;
  insert into exo.t_stock_movement (movement_type, lot_id, location_id, quantity, ref_type, ref_id, reason, created_by)
  values (p_type, p_lot_id, p_location_id, p_qty, p_ref_type, p_ref_id, p_reason, p_by);
end $$;

create or replace function exo.set_lot_status(p_lot_id bigint, p_to text, p_reason text, p_by text) returns void
language plpgsql volatile set search_path = '' as $$
declare v_from text;
begin
  select status into v_from from exo.t_lot where id = p_lot_id for update;
  update exo.t_lot set status = p_to, status_reason = p_reason where id = p_lot_id;
  insert into exo.t_lot_status_history (lot_id, from_status, to_status, reason, changed_by)
  values (p_lot_id, v_from, p_to, p_reason, p_by);
end $$;

/** 出荷明細の返品数量。p_recall: null=すべて、true=回収品のみ、false=通常返品のみ */
create or replace function exo.returned_qty(p_line_id bigint, p_recall boolean default null) returns integer
language sql stable set search_path = '' as $$
  select coalesce(sum(r.quantity), 0)::integer from exo.t_return r
  where r.shipment_line_id = p_line_id
    and (p_recall is null or (p_recall and r.recall_target_id is not null) or (not p_recall and r.recall_target_id is null))
$$;

/** ロットが対象になっている未完了の回収案件 */
create or replace function exo.open_recall_ids(p_lot_id bigint) returns setof bigint
language sql stable set search_path = '' as $$
  select rl.recall_id from exo.t_recall_lot rl join exo.t_recall r on r.id = rl.recall_id
  where rl.lot_id = p_lot_id and r.status <> 'CLOSED' order by rl.recall_id
$$;

