/** p = { table: 'm_supplier' | 'm_product' | 'm_customer' | 'm_location', data: {...} } */
create or replace function public.save_master(p jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_table text := exo.j_text(p, 'table');
  d jsonb := coalesce(p -> 'data', '{}');
  v_id bigint;
  v_code text;
  v_name text := exo.j_text(d, 'name');
  v_active boolean := case when exo.j_text(d, 'is_active') is null then true else exo.j_bool(d, 'is_active') end;
  v_n1 numeric; v_n2 numeric; v_n3 numeric; v_n4 numeric;
  v_type text; v_class text; v_reg text;
  v_has_stock boolean;
  v_row jsonb;
begin
  perform exo.require_user();
  perform exo.write_lock();
  if v_table is null or v_table not in ('m_supplier', 'm_product', 'm_customer', 'm_location') then
    perform exo.fail('更新できないテーブルです: ' || coalesce(v_table, ''));
  end if;
  v_code := exo.j_text(d, replace(v_table, 'm_', '') || '_code');
  if exo.j_text(d, 'id') is not null then
    v_id := exo.j_id(d, 'id');
    if v_id is null then perform exo.fail('データが見つかりません。画面を再読込してください。'); end if;
  end if;
  if v_code is null or v_name is null then perform exo.fail('コードと名称は必須です。'); end if;
  if v_code !~ '^[A-Za-z0-9-]+$' then perform exo.fail('コードは英数字とハイフンのみ使用できます。'); end if;

  if v_table = 'm_supplier' then
    if exists (select 1 from exo.m_supplier where upper(supplier_code) = upper(v_code) and id is distinct from v_id) then
      perform exo.fail('コード「' || v_code || '」は既に使われています。');
    end if;
    if v_id is null then
      insert into exo.m_supplier (supplier_code, name, contact_name, phone, email, is_active)
      values (v_code, v_name, exo.j_text(d, 'contact_name'), exo.j_text(d, 'phone'), exo.j_text(d, 'email'), v_active)
      returning to_jsonb(m_supplier.*) into v_row;
    else
      update exo.m_supplier set supplier_code = v_code, name = v_name, contact_name = exo.j_text(d, 'contact_name'),
        phone = exo.j_text(d, 'phone'), email = exo.j_text(d, 'email'), is_active = v_active, updated_at = now()
      where id = v_id returning to_jsonb(m_supplier.*) into v_row;
    end if;

  elsif v_table = 'm_product' then
    if exists (select 1 from exo.m_product where upper(product_code) = upper(v_code) and id is distinct from v_id) then
      perform exo.fail('コード「' || v_code || '」は既に使われています。');
    end if;
    v_class := exo.j_text(d, 'storage_class');
    v_reg := exo.j_text(d, 'regulatory_class');
    if v_class is null or not (exo.codes() -> 'storage_class' ? v_class) then perform exo.fail('保管温度区分を選択してください。'); end if;
    if v_reg is null or not (exo.codes() -> 'regulatory_class' ? v_reg) then perform exo.fail('規制区分を選択してください。'); end if;
    v_n1 := exo.j_num(d, 'shelf_life_days');
    if v_n1 is null or v_n1 = 'NaN' or v_n1 <= 0 or v_n1 <> trunc(v_n1) or v_n1 > 36500 then
      perform exo.fail('有効期間（日）を1以上の整数で入力してください。');
    end if;
    v_n2 := coalesce(exo.j_num(d, 'min_remaining_days'), 90);
    if v_n2 = 'NaN' or v_n2 < 0 or v_n2 <> trunc(v_n2) or v_n2 > 36500 then perform exo.fail('最低出荷残期間（日）は0以上の整数で入力してください。'); end if;
    v_n3 := exo.j_num(d, 'list_price');
    if v_n3 = 'NaN' or v_n3 < 0 or v_n3 >= 10000000000 then perform exo.fail('標準売価は0以上の数値で入力してください。'); end if;
    v_n4 := exo.j_num(d, 'reorder_point');
    if v_n4 = 'NaN' or v_n4 < 0 or v_n4 <> trunc(v_n4) or v_n4 > 1000000000 then perform exo.fail('発注点は0以上の整数で入力してください。'); end if;
    if v_id is not null and exists (select 1 from exo.m_product where id = v_id and storage_class <> v_class)
       and exists (select 1 from exo.t_inventory i join exo.t_lot l on l.id = i.lot_id where l.product_id = v_id and i.on_hand_qty > 0) then
      perform exo.fail('在庫がある商品の保管温度区分は変更できません。');
    end if;
    if v_id is null then
      insert into exo.m_product (product_code, name, storage_class, shelf_life_days, min_remaining_days, regulatory_class, list_price, reorder_point, is_active)
      values (v_code, v_name, v_class, v_n1, v_n2, v_reg, round(v_n3, 2), v_n4, v_active)
      returning to_jsonb(m_product.*) into v_row;
    else
      update exo.m_product set product_code = v_code, name = v_name, storage_class = v_class, shelf_life_days = v_n1,
        min_remaining_days = v_n2, regulatory_class = v_reg, list_price = round(v_n3, 2), reorder_point = v_n4,
        is_active = v_active, updated_at = now()
      where id = v_id returning to_jsonb(m_product.*) into v_row;
    end if;

  elsif v_table = 'm_customer' then
    if exists (select 1 from exo.m_customer where upper(customer_code) = upper(v_code) and id is distinct from v_id) then
      perform exo.fail('コード「' || v_code || '」は既に使われています。');
    end if;
    v_type := exo.j_text(d, 'customer_type');
    if v_type is null or not (exo.codes() -> 'customer_type' ? v_type) then perform exo.fail('顧客区分を選択してください。'); end if;
    if v_type = 'MEDICAL' and exo.j_text(d, 'medical_inst_code') is null then
      perform exo.fail('医療機関の場合、医療機関コードは必須です（BR-10）。');
    end if;
    if exo.j_text(d, 'address') is null then perform exo.fail('住所は必須です。'); end if;
    if v_id is null then
      insert into exo.m_customer (customer_code, name, customer_type, medical_inst_code, address, contact_name, phone, email, is_active)
      values (v_code, v_name, v_type, exo.j_text(d, 'medical_inst_code'), exo.j_text(d, 'address'), exo.j_text(d, 'contact_name'),
        exo.j_text(d, 'phone'), exo.j_text(d, 'email'), v_active)
      returning to_jsonb(m_customer.*) into v_row;
    else
      update exo.m_customer set customer_code = v_code, name = v_name, customer_type = v_type,
        medical_inst_code = exo.j_text(d, 'medical_inst_code'), address = exo.j_text(d, 'address'),
        contact_name = exo.j_text(d, 'contact_name'), phone = exo.j_text(d, 'phone'), email = exo.j_text(d, 'email'),
        is_active = v_active, updated_at = now()
      where id = v_id returning to_jsonb(m_customer.*) into v_row;
    end if;

  else -- m_location
    if exists (select 1 from exo.m_location where upper(location_code) = upper(v_code) and id is distinct from v_id) then
      perform exo.fail('コード「' || v_code || '」は既に使われています。');
    end if;
    v_class := exo.j_text(d, 'storage_class');
    if v_class is null or not (exo.codes() -> 'storage_class' ? v_class) then perform exo.fail('保管温度区分を選択してください。'); end if;
    v_n1 := exo.j_num(d, 'temp_min');
    v_n2 := exo.j_num(d, 'temp_max');
    if v_n1 is null or v_n2 is null or v_n1 = 'NaN' or v_n2 = 'NaN' or not (v_n1 < v_n2) or abs(v_n1) > 1000 or abs(v_n2) > 1000 then
      perform exo.fail('許容温度は 下限 < 上限 で入力してください。');
    end if;
    if v_id is not null then
      v_has_stock := exists (select 1 from exo.t_inventory where location_id = v_id and on_hand_qty > 0);
      if v_has_stock and not v_active then perform exo.fail('在庫がある保管場所は無効化できません。'); end if;
      if v_has_stock and exists (select 1 from exo.m_location where id = v_id
          and (storage_class <> v_class or is_quarantine <> exo.j_bool(d, 'is_quarantine'))) then
        perform exo.fail('在庫がある保管場所は、保管温度区分と隔離区分を変更できません。');
      end if;
    end if;
    if v_id is null then
      insert into exo.m_location (location_code, name, storage_class, temp_min, temp_max, is_quarantine, is_active)
      values (v_code, v_name, v_class, v_n1, v_n2, exo.j_bool(d, 'is_quarantine'), v_active)
      returning to_jsonb(m_location.*) into v_row;
    else
      update exo.m_location set location_code = v_code, name = v_name, storage_class = v_class, temp_min = v_n1, temp_max = v_n2,
        is_quarantine = exo.j_bool(d, 'is_quarantine'), is_active = v_active, updated_at = now()
      where id = v_id returning to_jsonb(m_location.*) into v_row;
    end if;
  end if;

  if v_row is null then perform exo.fail('データが見つかりません。画面を再読込してください。'); end if;
  return v_row - 'created_at' - 'updated_at';
end $$;

/** p = { regulatoryClass, customerType, allowed } */
create or replace function public.save_sales_rule(p jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_rc text := exo.j_text(p, 'regulatoryClass');
  v_ct text := exo.j_text(p, 'customerType');
begin
  perform exo.require_user();
  perform exo.write_lock();
  if v_rc is null or not (exo.codes() -> 'regulatory_class' ? v_rc) or v_ct is null or not (exo.codes() -> 'customer_type' ? v_ct) then
    perform exo.fail('規制区分または顧客区分が不正です。');
  end if;
  insert into exo.m_sales_rule (regulatory_class, customer_type, allowed) values (v_rc, v_ct, exo.j_bool(p, 'allowed'))
  on conflict (regulatory_class, customer_type) do update set allowed = excluded.allowed, updated_at = now();
  return 'true'::jsonb;
end $$;

-- ---- 入荷・検品（P-01 / P-02 / P-15 の簡易版） ----

/** p = { supplierId, productId, supplierLotNo, receiptDate, manufacturedOn, expiresOn, quantity, unitPrice, arrivalTemp, locationId } */
create or replace function public.register_receipt(p jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_user text := exo.require_user();
  v_today date := exo.today();
  v_product exo.m_product;
  v_supplier exo.m_supplier;
  v_loc exo.m_location;
  v_lot exo.t_lot;
  v_qty integer;
  v_price numeric := exo.j_num(p, 'unitPrice');
  v_temp numeric := exo.j_num(p, 'arrivalTemp');
  v_sup_lot text := exo.j_text(p, 'supplierLotNo');
  v_date date := exo.to_date(exo.j_text(p, 'receiptDate'));
  v_mfg date := exo.to_date(exo.j_text(p, 'manufacturedOn'));
  v_exp date;
  v_stock integer;
  v_head text;
  v_receipt_id bigint;
  v_receipt_no text;
  v_warning text := '';
begin
  perform exo.write_lock();
  select * into v_product from exo.m_product where id = exo.j_id(p, 'productId');
  if v_product.id is null then perform exo.fail('商品が見つかりません。画面を再読込してください。'); end if;
  select * into v_supplier from exo.m_supplier where id = exo.j_id(p, 'supplierId');
  if v_supplier.id is null then perform exo.fail('仕入先が見つかりません。画面を再読込してください。'); end if;
  select * into v_loc from exo.m_location where id = exo.j_id(p, 'locationId');
  if v_loc.id is null then perform exo.fail('保管場所が見つかりません。画面を再読込してください。'); end if;
  if not v_product.is_active then perform exo.fail('商品「' || v_product.name || '」は無効化されています。'); end if;
  if not v_supplier.is_active then perform exo.fail('仕入先「' || v_supplier.name || '」は無効化されています。'); end if;
  v_qty := exo.pos_int(exo.j_num(p, 'quantity'), '入荷数量');
  if v_price is null or v_price = 'NaN' or v_price < 0 or v_price >= 1000000000000 then
    perform exo.fail('仕入単価は0以上で入力してください。');
  end if;
  v_price := round(v_price, 2);
  if v_sup_lot is null then perform exo.fail('仕入先ロット番号を入力してください。'); end if;
  if length(v_sup_lot) > 100 then perform exo.fail('仕入先ロット番号は100文字以内で入力してください。'); end if;
  if v_date is null or v_date > v_today then perform exo.fail('入荷日は当日以前の日付を入力してください。'); end if;
  if exo.j_text(p, 'manufacturedOn') is not null and (v_mfg is null or v_mfg > v_date) then
    perform exo.fail('製造日は入荷日以前の日付を入力してください。');
  end if;
  if exo.j_text(p, 'expiresOn') is not null then
    v_exp := exo.to_date(exo.j_text(p, 'expiresOn'));
  elsif v_mfg is not null then
    v_exp := v_mfg + v_product.shelf_life_days;
  end if;
  if v_exp is null then perform exo.fail('使用期限を入力してください（製造日が不明な場合は必須）。'); end if;
  if v_exp <= v_date then perform exo.fail('使用期限は入荷日より後の日付を入力してください。'); end if;
  if v_temp = 'NaN' or abs(v_temp) > 1000 then perform exo.fail('到着時温度は数値（℃）で入力してください。'); end if;
  if v_loc.storage_class <> v_product.storage_class or v_loc.is_quarantine or not v_loc.is_active then
    perform exo.fail('保管場所「' || v_loc.name || '」には入庫できません（温度区分が商品と異なるか、隔離保管場所です）。');
  end if;

  select * into v_lot from exo.t_lot
  where supplier_id = v_supplier.id and product_id = v_product.id and supplier_lot_no = v_sup_lot for update;
  if v_lot.id is not null then
    if v_lot.expires_on <> v_exp then
      perform exo.fail('仕入先ロット番号「' || v_sup_lot || '」は既に使用期限 ' || v_lot.expires_on || ' で登録されています。使用期限を確認してください。');
    end if;
    if v_lot.status = 'VOID' then
      perform exo.set_lot_status(v_lot.id, 'QUARANTINE', '再入荷', v_user);
    elsif v_lot.status <> 'QUARANTINE' then
      perform exo.fail('ロット「' || v_lot.lot_no || '」は' || exo.code_label('lot_status', v_lot.status) || 'のため、簡易版では追加入荷できません。' ||
        '（合格済ロットへの分納はQA確認が必要です。仕入先に確認のうえ別の仕入先ロット番号で登録してください）');
    end if;
    select coalesce(sum(on_hand_qty), 0) into v_stock from exo.t_inventory where lot_id = v_lot.id;
    update exo.t_lot set unit_cost = round((v_stock * unit_cost + v_qty * v_price) / (v_stock + v_qty), 2) where id = v_lot.id;
  else
    v_head := v_product.product_code || '-' || to_char(v_date, 'YYMMDD') || '-';
    insert into exo.t_lot (lot_no, product_id, supplier_id, supplier_lot_no, manufactured_on, expires_on, received_on, unit_cost, status)
    values (v_head || lpad((coalesce((select max(substr(lot_no, length(v_head) + 1)::integer) from exo.t_lot
                                      where left(lot_no, length(v_head)) = v_head and substr(lot_no, length(v_head) + 1) ~ '^\d{1,9}$'), 0) + 1)::text, 2, '0'),
      v_product.id, v_supplier.id, v_sup_lot, v_mfg, v_exp, v_date, v_price, 'QUARANTINE')
    returning * into v_lot;
    insert into exo.t_lot_status_history (lot_id, from_status, to_status, reason, changed_by)
    values (v_lot.id, null, 'QUARANTINE', '入荷', v_user);
  end if;

  v_receipt_no := exo.next_no('RC', v_date, array(select receipt_no from exo.t_receipt));
  insert into exo.t_receipt (receipt_no, supplier_id, receipt_date, product_id, supplier_lot_no, manufactured_on, expires_on,
    arrival_temp, location_id, quantity, unit_price, lot_id, created_by)
  values (v_receipt_no, v_supplier.id, v_date, v_product.id, v_sup_lot, v_mfg, v_exp, v_temp, v_loc.id, v_qty, v_price, v_lot.id, v_user)
  returning id into v_receipt_id;
  perform exo.move('RECEIPT', v_lot.id, v_loc.id, v_qty, 'receipt', v_receipt_id, null, v_user);

  if v_temp is not null and (v_temp < v_loc.temp_min or v_temp > v_loc.temp_max) then
    v_warning := '到着時温度が許容範囲（' || v_loc.temp_min || '〜' || v_loc.temp_max || '℃）外です。検品時にQAが評価してください。';
  end if;
  return jsonb_build_object('receiptNo', v_receipt_no, 'lotNo', v_lot.lot_no, 'warning', v_warning);
end $$;

/** ロットステータス変更（受入検品 P-02 と QA によるステータス変更 P-15）。p = { lotId, to, reason, coaConfirmed } */
create or replace function public.change_lot_status(p jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_user text := exo.require_user();
  v_lot exo.t_lot;
  v_to text := exo.j_text(p, 'to');
  v_reason text := exo.j_text(p, 'reason');
  v_allowed jsonb := '{"QUARANTINE": ["RELEASED", "REJECTED", "HOLD"], "RELEASED": ["HOLD"], "HOLD": ["RELEASED", "QUARANTINE", "REJECTED"]}';
begin
  perform exo.write_lock();
  select * into v_lot from exo.t_lot where id = exo.j_id(p, 'lotId') for update;
  if v_lot.id is null then perform exo.fail('ロットが見つかりません。画面を再読込してください。'); end if;
  if v_to is null or not coalesce(v_allowed -> v_lot.status ? v_to, false) then
    perform exo.fail('現在のステータス（' || exo.code_label('lot_status', v_lot.status) || '）から「' ||
      coalesce(exo.code_label('lot_status', v_to), '') || '」には変更できません。');
  end if;
  if v_to = 'RELEASED' then
    if not exo.j_bool(p, 'coaConfirmed') then perform exo.fail('合格にはCOA（試験成績書）の確認が必要です（BR-08）。'); end if;
    if v_lot.status = 'HOLD' and v_lot.inspected_at is null then
      perform exo.fail('未検品のロットは「検品待ち」に戻してから検品してください（BR-17）。');
    end if;
    if v_lot.status = 'HOLD' and v_reason is null then perform exo.fail('保留解除の理由を入力してください。'); end if;
    if v_lot.expires_on < exo.today() then perform exo.fail('使用期限を過ぎたロットは合格にできません。'); end if;
  elsif v_reason is null then
    perform exo.fail('理由を入力してください。');
  end if;
  if v_lot.status = 'HOLD' and v_to = 'QUARANTINE' and v_lot.inspected_at is not null then
    perform exo.fail('検品済のロットは「合格」または「不合格」に変更してください。');
  end if;
  if v_lot.status = 'QUARANTINE' then
    update exo.t_lot set inspected_by = v_user, inspected_at = now() where id = v_lot.id;
  end if;
  perform exo.set_lot_status(v_lot.id, v_to, coalesce(v_reason, '検品合格（COA確認済）'), v_user);
  return exo.lot_view(v_lot.id);
end $$;

-- ---- 出荷（P-04 FEFO自動引当 ＋ P-05 出荷確定 を同時に実行） ----

/**
 * p = { customerId, shippedOn, note, lines: [{ productId, quantity, unitPrice }] }
 * 全明細の在庫が揃わない場合は何も登録しない（全量引当できたときだけ確定）。
 */
create or replace function public.create_shipment(p jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_user text := exo.require_user();
  v_customer exo.m_customer;
  v_product exo.m_product;
  v_shipped_on date := exo.to_date(exo.j_text(p, 'shippedOn'));
  v_lines jsonb := '[]';
  v_line jsonb;
  v_qty integer;
  v_price numeric;
  v_remain integer;
  v_take integer;
  v_avail integer;
  v_used jsonb := '{}';   -- 同一出荷内で既に割り当てた数量（在庫行ID → 数量）
  v_plan jsonb := '[]';
  v_i integer := 0;
  v_shipment_id bigint;
  v_line_id bigint;
  c record;
  a jsonb;
begin
  perform exo.write_lock();
  select * into v_customer from exo.m_customer where id = exo.j_id(p, 'customerId');
  if v_customer.id is null then perform exo.fail('顧客が見つかりません。画面を再読込してください。'); end if;
  if not v_customer.is_active then perform exo.fail('無効な顧客には出荷できません。'); end if;
  if v_shipped_on is null then perform exo.fail('出荷日を入力してください。'); end if;
  if jsonb_typeof(p -> 'lines') = 'array' then
    select coalesce(jsonb_agg(x order by o), '[]') into v_lines
    from jsonb_array_elements(p -> 'lines') with ordinality as e(x, o)
    where jsonb_typeof(x) = 'object' and exo.j_text(x, 'productId') is not null;
  end if;
  if jsonb_array_length(v_lines) = 0 then perform exo.fail('出荷明細を1行以上入力してください。'); end if;
  if jsonb_array_length(v_lines) > 100 then perform exo.fail('出荷明細は100行以内にしてください。'); end if;

  for v_line in select x from jsonb_array_elements(v_lines) x loop
    v_i := v_i + 1;
    select * into v_product from exo.m_product where id = exo.j_id(v_line, 'productId');
    if v_product.id is null then perform exo.fail('商品が見つかりません。画面を再読込してください。'); end if;
    if not v_product.is_active then perform exo.fail('商品「' || v_product.name || '」は無効化されています。'); end if;
    v_qty := exo.pos_int(exo.j_num(v_line, 'quantity'), v_i || '行目の数量');
    v_price := coalesce(exo.j_num(v_line, 'unitPrice'), v_product.list_price, 0);
    if v_price = 'NaN' or v_price < 0 or v_price >= 1000000000000 then perform exo.fail(v_i || '行目の単価が不正です。'); end if;
    v_price := round(v_price, 2);
    if not exists (select 1 from exo.m_sales_rule r where r.regulatory_class = v_product.regulatory_class
                   and r.customer_type = v_customer.customer_type and r.allowed) then
      perform exo.fail('商品「' || v_product.name || '」（' || exo.code_label('regulatory_class', v_product.regulatory_class) ||
        '）は顧客区分「' || exo.code_label('customer_type', v_customer.customer_type) || '」に販売できません（BR-09）。');
    end if;
    -- BR-04 引当可能在庫 → BR-05 FEFO（使用期限→入荷日→保管場所）
    v_remain := v_qty;
    for c in
      select i.id as inv_id, i.on_hand_qty, l.id as lot_id, l.unit_cost, loc.id as loc_id
      from exo.t_inventory i
      join exo.t_lot l on l.id = i.lot_id
      join exo.m_location loc on loc.id = i.location_id
      where l.product_id = v_product.id and l.status = 'RELEASED' and not loc.is_quarantine and i.on_hand_qty > 0
        and l.expires_on - v_shipped_on >= v_product.min_remaining_days
      order by l.expires_on, l.received_on, loc.id, l.id
      for update of i
    loop
      exit when v_remain <= 0;
      v_avail := c.on_hand_qty - coalesce((v_used ->> c.inv_id::text)::integer, 0);
      continue when v_avail <= 0;
      v_take := least(v_remain, v_avail);
      v_used := jsonb_set(v_used, array[c.inv_id::text], to_jsonb(coalesce((v_used ->> c.inv_id::text)::integer, 0) + v_take));
      v_plan := v_plan || jsonb_build_array(jsonb_build_object('product_id', v_product.id, 'lot_id', c.lot_id, 'loc_id', c.loc_id,
        'qty', v_take, 'price', v_price, 'cost', c.unit_cost));
      v_remain := v_remain - v_take;
    end loop;
    if v_remain > 0 then
      perform exo.fail('商品「' || v_product.name || '」の引当可能在庫が不足しています（不足 ' || v_remain || '）。' ||
        '合格済・残期間 ' || v_product.min_remaining_days || '日以上・隔離保管場所以外の在庫のみ引当できます。');
    end if;
  end loop;

  insert into exo.t_shipment (shipment_no, customer_id, shipped_on, status, note, created_by)
  values (exo.next_no('SH', v_shipped_on, array(select shipment_no from exo.t_shipment)), v_customer.id, v_shipped_on, 'SHIPPED',
    left(exo.j_text(p, 'note'), 1000), v_user)
  returning id into v_shipment_id;
  for a in select x from jsonb_array_elements(v_plan) x loop
    insert into exo.t_shipment_line (shipment_id, product_id, lot_id, location_id, quantity, unit_price, unit_cost, status)
    values (v_shipment_id, (a ->> 'product_id')::bigint, (a ->> 'lot_id')::bigint, (a ->> 'loc_id')::bigint, (a ->> 'qty')::integer,
      (a ->> 'price')::numeric, (a ->> 'cost')::numeric, 'SHIPPED')
    returning id into v_line_id;
    perform exo.move('SHIPMENT', (a ->> 'lot_id')::bigint, (a ->> 'loc_id')::bigint, -(a ->> 'qty')::integer, 'shipment_line', v_line_id, null, v_user);
  end loop;
  return exo.shipment_view(v_shipment_id);
end $$;

/** 出荷取消（P-06）：赤伝で在庫を戻す。返品がある出荷は取消不可。p = { shipmentId, reason } */
create or replace function public.cancel_shipment(p jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_user text := exo.require_user();
  v_ship exo.t_shipment;
  v_reason text := exo.j_text(p, 'reason');
  l record;
  v_recall bigint;
begin
  perform exo.write_lock();
  select * into v_ship from exo.t_shipment where id = exo.j_id(p, 'shipmentId') for update;
  if v_ship.id is null then perform exo.fail('出荷が見つかりません。画面を再読込してください。'); end if;
  if v_ship.status <> 'SHIPPED' then perform exo.fail('この出荷は既に取消されています。'); end if;
  if v_reason is null then perform exo.fail('取消理由を入力してください。'); end if;
  if exists (select 1 from exo.t_shipment_line sl join exo.t_return r on r.shipment_line_id = sl.id where sl.shipment_id = v_ship.id) then
    perform exo.fail('返品が登録されている出荷は取消できません。');
  end if;
  for l in select * from exo.t_shipment_line where shipment_id = v_ship.id and status = 'SHIPPED' order by id loop
    perform exo.move('CANCEL', l.lot_id, l.location_id, l.quantity, 'shipment_line', l.id, v_reason, v_user);
    update exo.t_shipment_line set status = 'CANCELLED' where id = l.id;
  end loop;
  update exo.t_shipment set status = 'CANCELLED', note = coalesce(note || ' / ', '') || '取消：' || v_reason where id = v_ship.id;
  for v_recall in select distinct x from exo.t_shipment_line sl, exo.open_recall_ids(sl.lot_id) x where sl.shipment_id = v_ship.id loop
    perform exo.extract_targets(v_recall);
  end loop;
  return exo.shipment_view(v_ship.id);
end $$;

-- ---- 返品（P-07 の簡易版：登録と処置判定を同時に行う） ----

/**
 * p = { shipmentLineId, quantity, reason, returnedOn, quarantineLocationId, disposition: 'RESTOCK'|'DISPOSE', restockLocationId }
 * 回収中ロットの返品は自動的に回収品として扱い、処置は廃棄のみ（BR-18）。
 */
create or replace function public.register_return(p jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_user text := exo.require_user();
  v_line exo.t_shipment_line;
  v_ship exo.t_shipment;
  v_lot exo.t_lot;
  v_product exo.m_product;
  v_qloc exo.m_location;
  v_rloc exo.m_location;
  v_qty integer;
  v_returnable integer;
  v_reason text := exo.j_text(p, 'reason');
  v_returned_on date;
  v_target exo.t_recall_target;
  v_disp text := exo.j_text(p, 'disposition');
  v_return_id bigint;
  v_return_no text;
  v_recovered integer;
  v_recall bigint;
begin
  perform exo.write_lock();
  select * into v_line from exo.t_shipment_line where id = exo.j_id(p, 'shipmentLineId') for update;
  if v_line.id is null then perform exo.fail('出荷明細が見つかりません。画面を再読込してください。'); end if;
  if v_line.status <> 'SHIPPED' then perform exo.fail('取消済の出荷明細には返品を登録できません。'); end if;
  select * into v_ship from exo.t_shipment where id = v_line.shipment_id;
  select * into v_lot from exo.t_lot where id = v_line.lot_id;
  select * into v_product from exo.m_product where id = v_line.product_id;
  v_qty := exo.pos_int(exo.j_num(p, 'quantity'), '返品数量');
  v_returnable := v_line.quantity - exo.returned_qty(v_line.id);
  if v_qty > v_returnable then perform exo.fail('返品数量が返品可能数（' || v_returnable || '）を超えています（BR-12）。'); end if;
  if v_reason is null then perform exo.fail('返品理由を入力してください。'); end if;
  if exo.j_text(p, 'returnedOn') is null then
    v_returned_on := exo.today();
  else
    v_returned_on := exo.to_date(exo.j_text(p, 'returnedOn'));
    if v_returned_on is null then perform exo.fail('返品日が不正です。'); end if;
  end if;
  if v_returned_on < v_ship.shipped_on or v_returned_on > exo.today() then
    perform exo.fail('返品日は出荷日（' || v_ship.shipped_on || '）以降、当日以前の日付を入力してください。');
  end if;
  select * into v_qloc from exo.m_location where id = exo.j_id(p, 'quarantineLocationId');
  if v_qloc.id is null then perform exo.fail('受入保管場所が見つかりません。画面を再読込してください。'); end if;
  if not v_qloc.is_quarantine or v_qloc.storage_class <> v_product.storage_class or not v_qloc.is_active then
    perform exo.fail('受入保管場所は、商品と同じ温度区分の隔離保管場所を選択してください。');
  end if;

  -- 回収中ロットなら回収対象に紐づける（P-07 ステップ2）
  select t.* into v_target from exo.t_recall_target t
  where t.recall_id in (select exo.open_recall_ids(v_lot.id)) and t.customer_id = v_ship.customer_id and t.lot_id = v_lot.id
  order by t.recall_id limit 1 for update;
  if v_target.id is not null then v_disp := 'DISPOSE'; end if;
  if v_disp is null or v_disp not in ('RESTOCK', 'DISPOSE') then perform exo.fail('処置（在庫戻し／廃棄）を選択してください。'); end if;
  if v_disp = 'RESTOCK' then
    if v_lot.status <> 'RELEASED' then
      perform exo.fail('ロットが合格（RELEASED）ではないため在庫に戻せません。廃棄を選択してください。');
    end if;
    select * into v_rloc from exo.m_location where id = exo.j_id(p, 'restockLocationId');
    if v_rloc.id is null then perform exo.fail('戻し保管場所が見つかりません。画面を再読込してください。'); end if;
    if v_rloc.is_quarantine or v_rloc.storage_class <> v_product.storage_class or not v_rloc.is_active then
      perform exo.fail('戻し保管場所は、商品と同じ温度区分の通常保管場所を選択してください。');
    end if;
  end if;

  v_return_no := exo.next_no('RT', v_returned_on, array(select return_no from exo.t_return));
  insert into exo.t_return (return_no, shipment_line_id, recall_target_id, returned_on, quantity, reason, disposition,
    location_id, restock_location_id, created_by)
  values (v_return_no, v_line.id, v_target.id, v_returned_on, v_qty, v_reason, v_disp, v_qloc.id, v_rloc.id, v_user)
  returning id into v_return_id;
  perform exo.move('RETURN', v_lot.id, v_qloc.id, v_qty, 'return', v_return_id, null, v_user);
  if v_disp = 'RESTOCK' then
    perform exo.move('TRANSFER_OUT', v_lot.id, v_qloc.id, -v_qty, 'return', v_return_id, null, v_user);
    perform exo.move('TRANSFER_IN', v_lot.id, v_rloc.id, v_qty, 'return', v_return_id, null, v_user);
  else
    perform exo.move('DISPOSE', v_lot.id, v_qloc.id, -v_qty, 'return', v_return_id, '返品廃棄：' || v_reason, v_user);
  end if;

  if v_target.id is not null then
    select coalesce(sum(quantity), 0) into v_recovered from exo.t_return where recall_target_id = v_target.id;
    update exo.t_recall_target set recovered_qty = v_recovered,
      unrecoverable_qty = least(unrecoverable_qty, greatest(shipped_qty - v_recovered, 0)),
      status = case when status <> 'CLOSED' and v_recovered + least(unrecoverable_qty, greatest(shipped_qty - v_recovered, 0)) >= shipped_qty
                    then 'RECOVERED' else status end,
      updated_at = now()
    where id = v_target.id;
  else
    for v_recall in select exo.open_recall_ids(v_lot.id) loop
      perform exo.extract_targets(v_recall);
    end loop;
  end if;
  return jsonb_build_object('returnNo', v_return_no, 'recall', v_target.id is not null, 'disposition', v_disp);
end $$;

