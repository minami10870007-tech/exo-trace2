create or replace function exo.shipment_view(p_shipment_id bigint) returns jsonb
language sql stable set search_path = '' as $$
  with lines as (
    select sl.id, jsonb_build_object(
        'id', sl.id, 'product', p.name, 'lot_no', l.lot_no, 'expires_on', l.expires_on,
        'lot_status', exo.code_label('lot_status', l.status), 'lot_status_code', l.status,
        'quantity', sl.quantity, 'unit_price', sl.unit_price, 'returned', exo.returned_qty(sl.id),
        'returnable', case when sl.status = 'SHIPPED' then sl.quantity - exo.returned_qty(sl.id) else 0 end,
        'status', sl.status) as j,
      sl.quantity * sl.unit_price as amount
    from exo.t_shipment_line sl
    join exo.t_lot l on l.id = sl.lot_id
    join exo.m_product p on p.id = sl.product_id
    where sl.shipment_id = p_shipment_id
  )
  select jsonb_build_object(
    'id', s.id, 'shipment_no', s.shipment_no, 'customer', c.name, 'customer_id', s.customer_id,
    'shipped_on', s.shipped_on, 'status', s.status, 'note', s.note,
    'lines', coalesce((select jsonb_agg(j order by id) from lines), '[]'::jsonb),
    'amount', coalesce((select sum(amount) from lines), 0))
  from exo.t_shipment s join exo.m_customer c on c.id = s.customer_id
  where s.id = p_shipment_id
$$;

create or replace function exo.recall_view(p_recall_id bigint) returns jsonb
language sql stable set search_path = '' as $$
  with t as (
    select rt.*, c.name as customer, c.customer_code, c.contact_name, c.phone, c.email, l.lot_no
    from exo.t_recall_target rt
    join exo.m_customer c on c.id = rt.customer_id
    join exo.t_lot l on l.id = rt.lot_id
    where rt.recall_id = p_recall_id
  ), act as (select * from t where shipped_qty > 0)
  select jsonb_build_object(
    'id', r.id, 'recall_no', r.recall_no, 'title', r.title, 'reason', r.reason, 'severity', r.severity,
    'started_on', r.started_on, 'closed_on', r.closed_on, 'status', r.status,
    'lots', coalesce((select jsonb_agg(l.lot_no order by l.lot_no) from exo.t_recall_lot rl join exo.t_lot l on l.id = rl.lot_id
                      where rl.recall_id = r.id), '[]'::jsonb),
    'targets', coalesce((select jsonb_agg(jsonb_build_object(
        'id', t.id, 'recall_id', t.recall_id, 'customer_id', t.customer_id, 'lot_id', t.lot_id,
        'shipped_qty', t.shipped_qty, 'recovered_qty', t.recovered_qty, 'unrecoverable_qty', t.unrecoverable_qty,
        'contacted_on', t.contacted_on, 'contact_method', t.contact_method, 'status', t.status, 'close_reason', t.close_reason,
        'customer', t.customer, 'customer_code', t.customer_code, 'contact_name', t.contact_name, 'phone', t.phone,
        'email', t.email, 'lot_no', t.lot_no, 'statusLabel', exo.code_label('target_status', t.status)) order by t.id) from t), '[]'::jsonb),
    'contactedRate', case when (select count(*) from act) = 0 then 100
      else round(100.0 * (select count(*) from act where status <> 'NOT_CONTACTED') / (select count(*) from act)) end,
    'recoveredRate', case when coalesce((select sum(shipped_qty) from act), 0) = 0 then 100
      else round(100.0 * (select sum(least(shipped_qty, recovered_qty + unrecoverable_qty)) from act) / (select sum(shipped_qty) from act)) end,
    'remainingStock', coalesce((select sum(i.on_hand_qty) from exo.t_recall_lot rl join exo.t_inventory i on i.lot_id = rl.lot_id
                               where rl.recall_id = r.id), 0))
  from exo.t_recall r where r.id = p_recall_id
$$;

/** 回収対象の抽出（SQL-03 相当。何度実行しても同じ結果） */
create or replace function exo.extract_targets(p_recall_id bigint) returns void
language plpgsql volatile set search_path = '' as $$
declare
  v_status text;
  rec record;
begin
  select status into v_status from exo.t_recall where id = p_recall_id for update;
  if v_status is null or v_status = 'CLOSED' then return; end if;
  for rec in
    with net as (  -- 顧客 × ロットの出荷正味数量（出荷 − 通常返品）
      select s.customer_id, sl.lot_id, sum(sl.quantity - exo.returned_qty(sl.id, false))::integer as qty
      from exo.t_shipment_line sl
      join exo.t_shipment s on s.id = sl.shipment_id
      where sl.status = 'SHIPPED' and sl.lot_id in (select lot_id from exo.t_recall_lot where recall_id = p_recall_id)
      group by s.customer_id, sl.lot_id
    )
    select coalesce(n.customer_id, t.customer_id) as customer_id, coalesce(n.lot_id, t.lot_id) as lot_id,
      coalesce(n.qty, 0) as qty, t.id as target_id, t.recovered_qty, t.unrecoverable_qty, t.status
    from net n
    full join (select * from exo.t_recall_target where recall_id = p_recall_id) t
      on t.customer_id = n.customer_id and t.lot_id = n.lot_id
  loop
    if rec.target_id is null then
      insert into exo.t_recall_target (recall_id, customer_id, lot_id, shipped_qty, status, close_reason)
      values (p_recall_id, rec.customer_id, rec.lot_id, rec.qty,
        case when rec.qty > 0 then 'NOT_CONTACTED' else 'CLOSED' end,
        case when rec.qty > 0 then null else '自動：出荷正味0' end);
    elsif rec.qty = 0 and rec.recovered_qty = 0 then
      update exo.t_recall_target set shipped_qty = 0, unrecoverable_qty = 0, status = 'CLOSED', close_reason = '自動：出荷正味0', updated_at = now()
      where id = rec.target_id;
    else
      update exo.t_recall_target set shipped_qty = rec.qty,
        unrecoverable_qty = least(unrecoverable_qty, greatest(rec.qty - recovered_qty, 0)),
        status = case when status = 'CLOSED' then status
                      when recovered_qty + least(unrecoverable_qty, greatest(rec.qty - recovered_qty, 0)) >= rec.qty then 'RECOVERED'
                      when status = 'RECOVERED' then case when contacted_on is not null then 'CONTACTED' else 'NOT_CONTACTED' end
                      else status end,
        updated_at = now()
      where id = rec.target_id;
    end if;
  end loop;
  if v_status = 'OPEN' then
    update exo.t_recall set status = 'IN_PROGRESS' where id = p_recall_id;
  end if;
end $$;

/** 日次チェック（B-01 期限切れ判定 ／ B-03 在庫整合性チェック）。pg_cron で毎日 1:00（日本時間）に実行 */
create or replace function exo.daily_check() returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_today date := exo.today();
  v_expired jsonb := '[]';
  v_mismatch jsonb;
  v_result jsonb;
  rec record;
begin
  perform exo.write_lock();
  for rec in select id, lot_no from exo.t_lot
             where status in ('RELEASED', 'HOLD') and expires_on < v_today order by expires_on, id for update loop
    perform exo.set_lot_status(rec.id, 'EXPIRED', '期限到来（日次チェック）', 'system');
    v_expired := v_expired || to_jsonb(rec.lot_no);
  end loop;
  select coalesce(jsonb_agg(jsonb_build_object('lot_no', l.lot_no, 'location', loc.name,
           'on_hand', x.on_hand, 'movement_total', x.moved) order by l.lot_no, loc.name), '[]'::jsonb)
  into v_mismatch
  from (
    select coalesce(i.lot_id, m.lot_id) as lot_id, coalesce(i.location_id, m.location_id) as location_id,
      coalesce(i.on_hand_qty, 0) as on_hand, coalesce(m.total, 0) as moved
    from exo.t_inventory i
    full join (select lot_id, location_id, sum(quantity) as total from exo.t_stock_movement group by lot_id, location_id) m
      on m.lot_id = i.lot_id and m.location_id = i.location_id
    where coalesce(i.on_hand_qty, 0) <> coalesce(m.total, 0)
  ) x
  join exo.t_lot l on l.id = x.lot_id
  join exo.m_location loc on loc.id = x.location_id;
  v_result := jsonb_build_object('expired', v_expired, 'mismatches', v_mismatch);
  insert into exo.t_job_log (job, result) values ('daily_check', v_result);
  delete from exo.t_job_log where job = 'daily_check' and ran_at < now() - interval '400 days';
  return v_result;
end $$;
revoke all on function exo.daily_check() from public;

