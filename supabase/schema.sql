/** p = { targetId, contactedOn, contactMethod, status: 'CONTACTED'|'CLOSED'|'', unrecoverableQty, closeReason } */
create or replace function public.update_recall_target(p jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_t exo.t_recall_target;
  v_recall_status text;
  v_contacted date;
  v_unrec numeric;
  v_status text;
  v_close text := exo.j_text(p, 'closeReason');
begin
  perform exo.require_user();
  perform exo.write_lock();
  select * into v_t from exo.t_recall_target where id = exo.j_id(p, 'targetId') for update;
  if v_t.id is null then perform exo.fail('回収対象が見つかりません。画面を再読込してください。'); end if;
  select status into v_recall_status from exo.t_recall where id = v_t.recall_id;
  if v_recall_status = 'CLOSED' then perform exo.fail('完了した回収案件は更新できません。'); end if;
  if p ? 'contactedOn' then
    v_contacted := exo.to_date(exo.j_text(p, 'contactedOn'));
    if exo.j_text(p, 'contactedOn') is not null and (v_contacted is null or v_contacted > exo.today()) then
      perform exo.fail('連絡日が不正です（当日以前の日付を入力してください）。');
    end if;
    v_t.contacted_on := v_contacted;
  end if;
  if p ? 'contactMethod' then v_t.contact_method := left(exo.j_text(p, 'contactMethod'), 50); end if;
  if exo.j_text(p, 'unrecoverableQty') is not null then
    v_unrec := exo.j_num(p, 'unrecoverableQty');
    if v_unrec = 'NaN' or v_unrec < 0 or v_unrec <> trunc(v_unrec) or v_unrec > 1000000000 then
      perform exo.fail('回収不能数量は0以上の整数で入力してください。');
    end if;
    if v_unrec + v_t.recovered_qty > v_t.shipped_qty then perform exo.fail('回収数量＋回収不能数量が出荷正味数量を超えています。'); end if;
    v_t.unrecoverable_qty := v_unrec;
  end if;
  v_status := exo.j_text(p, 'status');
  if v_status = 'CLOSED' then
    if v_close is null then perform exo.fail('クローズ理由を入力してください。'); end if;
    v_t.status := 'CLOSED';
    v_t.close_reason := left(v_close, 500);
  elsif v_status = 'CONTACTED' and v_t.status = 'NOT_CONTACTED' then
    v_t.status := 'CONTACTED';
  elsif v_status is not null and v_status not in ('CONTACTED', 'CLOSED') then
    perform exo.fail('状態が不正です。');
  end if;
  if v_t.status <> 'CLOSED' then
    if v_t.shipped_qty > 0 and v_t.recovered_qty + v_t.unrecoverable_qty >= v_t.shipped_qty then
      v_t.status := 'RECOVERED';
    elsif v_t.status = 'RECOVERED' then
      v_t.status := case when v_t.contacted_on is not null then 'CONTACTED' else 'NOT_CONTACTED' end;
    end if;
  end if;
  update exo.t_recall_target set contacted_on = v_t.contacted_on, contact_method = v_t.contact_method,
    unrecoverable_qty = v_t.unrecoverable_qty, status = v_t.status, close_reason = v_t.close_reason, updated_at = now()
  where id = v_t.id;
  return exo.recall_view(v_t.recall_id);
end $$;

/** p = { recallId } */
create or replace function public.close_recall(p jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_recall exo.t_recall;
  v_open integer;
  v_view jsonb;
begin
  perform exo.require_user();
  perform exo.write_lock();
  select * into v_recall from exo.t_recall where id = exo.j_id(p, 'recallId') for update;
  if v_recall.id is null then perform exo.fail('回収案件が見つかりません。画面を再読込してください。'); end if;
  if v_recall.status = 'CLOSED' then perform exo.fail('既に完了しています。'); end if;
  select count(*) into v_open from exo.t_recall_target where recall_id = v_recall.id and status not in ('RECOVERED', 'CLOSED');
  if v_open > 0 then perform exo.fail('未完了の回収対象顧客が ' || v_open || ' 件あるため完了できません。'); end if;
  update exo.t_recall set status = 'CLOSED', closed_on = exo.today() where id = v_recall.id;
  v_view := exo.recall_view(v_recall.id);
  return v_view || jsonb_build_object('warning', case when (v_view ->> 'remainingStock')::integer > 0
    then '回収対象ロットに未処分の在庫（' || (v_view ->> 'remainingStock') || '）が残っています。' else '' end);
end $$;

