    'product', p.name, 'product_code', p.product_code, 'supplier', s.name,
    'manufactured_on', l.manufactured_on, 'expires_on', l.expires_on, 'received_on', l.received_on,
    'daysLeft', l.expires_on - exo.today(), 'unit_cost', l.unit_cost,
    'status', l.status, 'statusLabel', exo.code_label('lot_status', l.status), 'status_reason', l.status_reason,
    'inspected_at', exo.fmt_ts(l.inspected_at),
    'stock', coalesce(inv.stock, 0), 'availableStock', coalesce(inv.avail, 0)) as j
from exo.t_lot l
join exo.m_product p on p.id = l.product_id
join exo.m_supplier s on s.id = l.supplier_id
left join lateral (
  select sum(i.on_hand_qty) as stock, sum(i.on_hand_qty) filter (where not loc.is_quarantine) as avail
  from exo.t_inventory i join exo.m_location loc on loc.id = i.location_id
  where i.lot_id = l.id
) inv on true;
revoke all on exo.v_lot from public;

