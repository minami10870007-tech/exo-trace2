# 17. 主要SQL（トレース）
# ---------------------------------------------------------------------------
# (SQL ID, 用途, SQL)
SQLS = [
    ("SQL-01", "ロット→出荷先顧客（前方追跡）",
     "SELECT c.customer_code, c.name AS customer_name, st.name AS ship_to_name, s.shipment_no, s.shipped_on,\n"
     "       sl.quantity AS shipped_qty,\n"
     "       COALESCE(SUM(r.quantity), 0) AS returned_qty,\n"
     "       sl.quantity - COALESCE(SUM(r.quantity), 0) AS net_qty\n"
     "FROM t_shipment_line sl\n"
     "JOIN t_shipment s ON s.id = sl.shipment_id AND s.status = 'SHIPPED'\n"
     "JOIN m_customer c ON c.id = s.customer_id\n"
     "JOIN m_ship_to st ON st.id = s.ship_to_id\n"
     "LEFT JOIN t_return r ON r.shipment_line_id = sl.id\n"
     "WHERE sl.lot_id = :lot_id\n"
     "GROUP BY c.customer_code, c.name, st.name, s.shipment_no, s.shipped_on, sl.id, sl.quantity\n"
     "ORDER BY s.shipped_on;"),
    ("SQL-02", "顧客→購入ロット（後方追跡）",
     "SELECT s.shipped_on, p.product_code, p.name AS product_name, l.lot_no, l.supplier_lot_no,\n"
     "       l.expires_on, l.status AS lot_status, sl.quantity\n"
     "FROM t_shipment s\n"
     "JOIN t_shipment_line sl ON sl.shipment_id = s.id\n"
     "JOIN t_lot l ON l.id = sl.lot_id\n"
     "JOIN m_product p ON p.id = sl.product_id\n"
     "WHERE s.customer_id = :customer_id AND s.status = 'SHIPPED'\n"
     "  AND s.shipped_on BETWEEN :from AND :to\n"
     "ORDER BY s.shipped_on DESC;"),
    ("SQL-03", "回収対象顧客抽出",
     "INSERT INTO t_recall_target (recall_id, customer_id, lot_id, shipped_qty, recovered_qty, status, created_by, updated_by)\n"
     "SELECT :recall_id, s.customer_id, sl.lot_id, SUM(sl.quantity) - COALESCE(SUM(rt.returned), 0), 0, 'NOT_CONTACTED', :user_id, :user_id\n"
     "FROM t_recall_lot rl\n"
     "JOIN t_shipment_line sl ON sl.lot_id = rl.lot_id\n"
     "JOIN t_shipment s ON s.id = sl.shipment_id AND s.status = 'SHIPPED'\n"
     "LEFT JOIN (SELECT shipment_line_id, SUM(quantity) AS returned FROM t_return GROUP BY shipment_line_id) rt\n"
     "       ON rt.shipment_line_id = sl.id\n"
     "WHERE rl.recall_id = :recall_id\n"
     "GROUP BY s.customer_id, sl.lot_id\n"
     "HAVING SUM(sl.quantity) - COALESCE(SUM(rt.returned), 0) > 0\n"
     "ON CONFLICT (recall_id, customer_id, lot_id) DO NOTHING;"),
    ("SQL-04", "在庫整合性チェック（日次バッチ）",
     "SELECT i.lot_id, i.location_id, i.on_hand_qty, COALESCE(SUM(m.quantity), 0) AS movement_total\n"
     "FROM t_inventory i\n"
     "LEFT JOIN t_stock_movement m ON m.lot_id = i.lot_id AND m.location_id = i.location_id\n"
     "GROUP BY i.lot_id, i.location_id, i.on_hand_qty\n"
     "HAVING i.on_hand_qty <> COALESCE(SUM(m.quantity), 0);"),
]

