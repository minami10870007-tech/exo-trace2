# 17. 主要SQL（トレース）
# ---------------------------------------------------------------------------
# (SQL ID, 用途, SQL)
SQLS = [
    ("SQL-01", "ロット→出荷先顧客（前方追跡）",
     "SELECT c.customer_code, c.name AS customer_name, st.name AS ship_to_name, s.shipment_no, s.shipped_on,\n"
     "       sl.quantity AS shipped_qty,\n"
     "       COALESCE(SUM(r.quantity), 0) AS returned_qty,\n"
     "       sl.quantity - COALESCE(SUM(r.quantity), 0) AS net_qty\n"
     "FROM t_shipment_line sl\n"
     "JOIN t_shipment s ON s.id = sl.shipment_id\n"
     "JOIN m_customer c ON c.id = s.customer_id\n"
     "JOIN m_ship_to st ON st.id = s.ship_to_id\n"
     "LEFT JOIN t_return r ON r.shipment_line_id = sl.id\n"
     "WHERE sl.lot_id = :lot_id AND sl.status = 'SHIPPED'\n"
     "GROUP BY c.customer_code, c.name, st.name, s.shipment_no, s.shipped_on, sl.id, sl.quantity\n"
     "ORDER BY s.shipped_on;"),
    ("SQL-02", "顧客→購入ロット（後方追跡）",
     "SELECT s.shipped_on, p.product_code, p.name AS product_name, l.lot_no, l.supplier_lot_no,\n"
     "       l.expires_on, l.status AS lot_status, sl.quantity AS shipped_qty,\n"
     "       COALESCE(SUM(r.quantity), 0) AS returned_qty,\n"
     "       sl.quantity - COALESCE(SUM(r.quantity), 0) AS net_qty\n"
     "FROM t_shipment s\n"
     "JOIN t_shipment_line sl ON sl.shipment_id = s.id AND sl.status = 'SHIPPED'\n"
     "JOIN t_lot l ON l.id = sl.lot_id\n"
     "JOIN m_product p ON p.id = sl.product_id\n"
     "LEFT JOIN t_return r ON r.shipment_line_id = sl.id\n"
     "WHERE s.customer_id = :customer_id\n"
     "  AND s.shipped_on BETWEEN :from AND :to\n"
     "GROUP BY s.shipped_on, p.product_code, p.name, l.lot_no, l.supplier_lot_no, l.expires_on, l.status, sl.id, sl.quantity\n"
     "ORDER BY s.shipped_on DESC;"),
    ("SQL-03", "回収対象顧客抽出（再実行可・冪等）",
     "-- shipped_qty＝出荷数量−通常返品数量（回収品の返品は recovered_qty 側で管理するため除外）\n"
     "INSERT INTO t_recall_target (recall_id, customer_id, ship_to_id, lot_id, shipped_qty, recovered_qty, status, created_by, updated_by)\n"
     "SELECT :recall_id, s.customer_id, s.ship_to_id, sl.lot_id,\n"
     "       SUM(sl.quantity - COALESCE(rt.returned, 0)), 0,\n"
     "       CASE WHEN SUM(sl.quantity - COALESCE(rt.returned, 0)) > 0 THEN 'NOT_CONTACTED' ELSE 'CLOSED' END,\n"
     "       :user_id, :user_id\n"
     "FROM t_recall_lot rl\n"
     "JOIN t_shipment_line sl ON sl.lot_id = rl.lot_id AND sl.status = 'SHIPPED'\n"
     "JOIN t_shipment s ON s.id = sl.shipment_id\n"
     "LEFT JOIN (SELECT shipment_line_id, SUM(quantity) AS returned FROM t_return\n"
     "           WHERE recall_target_id IS NULL GROUP BY shipment_line_id) rt\n"
     "       ON rt.shipment_line_id = sl.id\n"
     "WHERE rl.recall_id = :recall_id\n"
     "GROUP BY s.customer_id, s.ship_to_id, sl.lot_id\n"
     "ON CONFLICT (recall_id, ship_to_id, lot_id) DO UPDATE\n"
     "  SET shipped_qty = EXCLUDED.shipped_qty,\n"
     "      status = CASE WHEN EXCLUDED.shipped_qty = 0 THEN 'CLOSED' ELSE t_recall_target.status END,\n"
     "      updated_at = now(), updated_by = EXCLUDED.updated_by;"),
    ("SQL-04", "在庫整合性チェック：現在庫＝移動履歴合計（日次バッチ）",
     "WITH mv AS (\n"
     "  SELECT lot_id, location_id, SUM(quantity) AS total FROM t_stock_movement GROUP BY lot_id, location_id\n"
     ")\n"
     "SELECT COALESCE(i.lot_id, mv.lot_id) AS lot_id, COALESCE(i.location_id, mv.location_id) AS location_id,\n"
     "       COALESCE(i.on_hand_qty, 0) AS on_hand_qty, COALESCE(mv.total, 0) AS movement_total\n"
     "FROM t_inventory i\n"
     "FULL JOIN mv ON mv.lot_id = i.lot_id AND mv.location_id = i.location_id\n"
     "WHERE COALESCE(i.on_hand_qty, 0) <> COALESCE(mv.total, 0);"),
    ("SQL-05", "引当整合性チェック：引当済数＝ALLOCATED出荷明細合計（日次バッチ）",
     "SELECT i.lot_id, i.location_id, i.allocated_qty, COALESCE(a.qty, 0) AS allocated_lines\n"
     "FROM t_inventory i\n"
     "LEFT JOIN (SELECT lot_id, location_id, SUM(quantity) AS qty FROM t_shipment_line\n"
     "           WHERE status = 'ALLOCATED' GROUP BY lot_id, location_id) a\n"
     "       ON a.lot_id = i.lot_id AND a.location_id = i.location_id\n"
     "WHERE i.allocated_qty <> COALESCE(a.qty, 0);"),
]

